#include <bits/stdc++.h>

using namespace std ;
int ans = 0 ;
pair<int,int> mergesort(string& num,int start ,int stop){
    if (start == stop){
        if (num[start]=='0'){
            return {1,0};
        } else {
            return {0,1};
        }
    }
    int m = (start+stop)/2;
    auto [l0,l1] = mergesort(num,start,m);
    auto [r0,r1] = mergesort(num,m+1,stop);
    if (l0 == m - start +1){
        ans += (stop-start+1)-l0 ;
        return {l0+r0,l1+r1};
    } else if(r0 == stop - (m + 1) + 1){
        ans +=  (stop-start+1)-l0-r0;
        return {l0+r0,l1+r1};
    }
    ans+=(stop-start+1)-l0-r0-l1;
    return {l0+r0,l1+r1};
}

